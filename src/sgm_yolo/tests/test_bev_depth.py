def detection(x=320,y=240,category=2):
    return dict(x1=x-20.,y1=y-30.,x2=x+20.,y2=y+30.,category=category,score=.9)


class SnapshotMMIO:
    def __init__(self):
        self.registers={0xf0:SNAPSHOT_CAPABILITY,0xfc:0,0x10c:10,0x104:7,0x100:1}
        self.writes=[];self.hang=False
    def read(self,address):return self.registers.get(address,0)
    def write(self,address,value):
        self.writes.append((address,value));self.registers[address]=value
        if address==0xf4:
            self.registers[0x10c]=self.registers[0xf8]
            self.registers[0xfc]=1 if self.hang else 2
            self.registers[0x104]+=1
        if address==0x114 and value==self.registers[0x10c]:self.registers[0xfc]=0


class Display:
    def __init__(self):self.r={0x24c:0};self.frames=[]
    def read(self,address):
        if address==0x24c and self.r.get(address,0):
            if self.r[0x240]==1:
                self.r[0x250]=self.r[0x244];self.r[0x254]=self.r[0x248]
                self.frames.append((self.r[0x250],self.r[0x254]))
            else:self.r[0x250]=self.r[0x254]=0
            self.r[0x24c]=0
        return self.r.get(address,0)
    def write(self,address,value):
        self.r[address]=value
        if address==0x240:self.r[0x24c]=1


class BEVDepthTests(unittest.TestCase):
    def setUp(self):self.geometry=BEVGeometry.from_directory(ROOT/'hardware/calibration')

    def test_display_regeneration_preserves_production_bev2_wiring(self):
        from tools import generate_lds_net_wrappers as wrappers
        with patch.object(wrappers,'save') as save:
            wrappers.display()
        name,ports,body=save.call_args.args
        text='`timescale 1ns/1ps\n// Generated by tools/generate_lds_net_wrappers.py; interface wiring only.\n'
        text+=f'module {name}(\n'+',\n'.join(ports)+'\n);\n'+body+'endmodule\n'
        self.assertEqual(text,(ROOT/'hardware/rtl/lds_net/lds_net_display.v').read_text(encoding='utf-8'))

    def test_raw_centers_rectify_to_existing_full_maps(self):
        with np.load(ROOT/'hardware/calibration/fixed_rig_maps.npz') as maps:
            for u,v in ((200,100),(392,242),(530,370),(320,300),(100,200)):
                raw=(float(maps['left_x'][v,u]),float(maps['left_y'][v,u]))
                result=self.geometry.rectify(*raw)
                self.assertIsNotNone(result);np.testing.assert_allclose(result,[u,v],atol=.03)

    def test_robust_mean_and_unknown_depth(self):
        patch=np.full((5,5),3);patch[0,0]=63;patch[1,1]=0
        result=self.geometry.distance(patch)
        self.assertTrue(result['valid']);self.assertEqual(result['disparity'],3)
        intrinsics=json.loads((ROOT/'hardware/calibration/fixed_rig_intrinsics.json').read_text())
        self.assertAlmostEqual(result['distance_m'],abs(intrinsics['P_right'][0][3])/1000/3)
        self.assertFalse(self.geometry.distance(np.zeros((5,5)))['valid'])
        self.assertFalse(self.geometry.distance(np.array([1]*12+[63]*13))['valid'])
        # A stable disparity of one is a real (coarse) far measurement, not
        # missing depth. It must no longer disappear at the old 15 m cutoff.
        self.assertTrue(self.geometry.distance(np.ones((5,5)))['valid'])
        self.assertFalse(self.geometry.distance(None)['valid'])

    def test_projection_x_uses_only_raw_x_and_z_controls_vertical(self):
        boxes=[detection(y=100),detection(y=350)]
        snap=dict(centers=[(320,100),(320,350)],patches=[np.full((5,5),3),np.full((5,5),30)])
        values,targets=self.geometry.project(boxes,snap)
        self.assertEqual(targets[0]['display_center'][0],targets[1]['display_center'][0])
        self.assertLess(targets[0]['display_center'][1],targets[1]['display_center'][1])
        self.assertEqual(targets[1]['descriptor_slot'],0) # nearer first, even at lower confidence
        self.assertEqual(len(values),16)
        snap['patches']=[None,None]
        self.assertEqual(self.geometry.project(boxes,snap)[0],[0]*16)

    def test_far_measurements_remain_visible_in_order_and_shrink(self):
        # Real public sample depths include 15.88, 24.81, 28.12 and 80.05 m.
        calibration=dict(camera_matrix_left=np.eye(3).tolist(),distortion_left=[0]*5,
            R_left=np.eye(3).tolist(),P_left=np.c_[np.eye(3),np.zeros(3)].tolist(),
            P_right=[[1,0,0,-397039.748363007],[0,1,0,0],[0,0,1,0]])
        geometry=BEVGeometry(calibration)
        boxes=[detection() for _ in range(5)]
        values,targets=geometry.project(boxes,dict(centers=[(320,240)]*5,
            patches=[np.full((5,5),d) for d in (63,25,16,5,1)]))
        self.assertEqual(sum(bool(v) for v in values),5)
        self.assertTrue(all(t['valid'] for t in targets))
        centers=[t['display_center'][1] for t in targets]
        self.assertTrue(all(a>b for a,b in zip(centers,centers[1:])))
        self.assertGreater(centers[-1],35)
        self.assertEqual([t['size_grade'] for t in targets],[0,1,2,3,3])
        self.assertEqual([t['sprite_size'][0] for t in targets],[67,57,45,34,34])

    def test_scale_thresholds_and_descriptor_extents_for_both_kinds(self):
        for category in (0,2):
            kind=2 if category==0 else 1
            for z,grade in ((7.999,0),(8.,1),(19.999,1),(20.,2),(44.999,2),(45.,3),(1000.,3)):
                # Hold disparity at 1 and set fB to the desired metric depth.
                with patch.object(self.geometry,'fb',z):
                    values,targets=self.geometry.project([detection(x=630,category=category)],
                        dict(centers=[(630,240)],patches=[np.ones((5,5))]))
                word=values[0];target=targets[0]
                self.assertTrue(target['valid']);self.assertEqual((word>>19)&3,kind)
                self.assertEqual((word>>21)&3,grade)
                width,height=target['sprite_size']
                left=word&1023
                if left>=640:left-=1024
                self.assertAlmostEqual(left+width/2,630,delta=.5)
                self.assertLessEqual(((word>>10)&511)+height,480)
        with self.assertRaises(ValueError):BEVGeometry.from_directory(ROOT/'hardware/calibration',depth_scale=0)

    def test_horizontal_fraction_matches_left_image_at_all_sizes_and_edges(self):
        for category in (0,2):
            for x in (0,5,80,160,193.27217865,320,480,630,639):
                for z in (5.,12.,30.,80.):
                    with patch.object(self.geometry,'fb',z):
                        values,targets=self.geometry.project([detection(x=x,category=category)],
                            dict(centers=[(320,240)],patches=[np.ones((5,5))]))
                    target=targets[0];word=values[0]
                    self.assertTrue(target['valid'],(category,x,z,target))
                    self.assertEqual(target['display_center'][0],x)
                    left=word&1023
                    if left>=640:left-=1024
                    width=target['sprite_size'][0]
                    self.assertAlmostEqual((left+width/2)/640,x/640,delta=.5/640+1e-12)
                    self.assertLess(left,640);self.assertGreater(left+width,0)

    def test_select_limits_duplicates_and_malformed_inputs(self):
        self.assertEqual(len(select_targets([detection(),detection(),dict(score='bad'),detection(category=6)])),1)
        self.assertEqual(select_targets([dict(detection(),score=float('nan'))]),[])

    def test_snapshot_decodes_original_six_bit_disparity_and_releases(self):
        mmio=SnapshotMMIO();frames=[np.zeros((480,640),np.uint8) for _ in range(3)]
        frames[1][:]=(30<<2)|(30>>4)
        result=SGMSnapshot(mmio,frames).sample_next([(320,240),(0,0),None])
        np.testing.assert_array_equal(result['patches'][0],np.full((5,5),30))
        self.assertIsNone(result['patches'][1]);self.assertIsNone(result['patches'][2])
        self.assertEqual(mmio.writes[-1],(0x114,result['request_id']))
        self.assertEqual(result['sgm_sequence'],8)

    def test_snapshot_timeout_and_stop_cancel_token(self):
        mmio=SnapshotMMIO();mmio.hang=True
        provider=SGMSnapshot(mmio,[np.zeros((480,640),np.uint8)]*3)
        with self.assertRaises(TimeoutError):provider.sample_next([(320,240)],timeout=.005)
        self.assertEqual(mmio.read(0xfc),0)
        stopped=threading.Event();stopped.set()
        with self.assertRaises(SnapshotCancelled):provider.sample_next([(320,240)],stop=stopped)
        self.assertEqual(mmio.read(0xfc),0)

    def test_expiry_during_cache_sync_is_rejected(self):
        mmio=SnapshotMMIO();provider=SGMSnapshot(mmio,[np.zeros((480,640),np.uint8)]*3)
        provider._invalidate=lambda *args:mmio.registers.update({0xfc:16})
        with self.assertRaisesRegex(RuntimeError,'lease lost'):provider.sample_next([(320,240)])
        self.assertEqual(mmio.read(0xfc),0)

    def test_latest_pending_job_drops_intermediate_without_blocking_submit(self):
        gate=threading.Event();entered=threading.Event()
        class Provider:
            def __init__(self):self.calls=0
            def sample_next(self,points,**kwargs):
                self.calls+=1;entered.set();gate.wait(1)
                return dict(request_id=self.calls,sgm_sequence=100+self.calls,centers=points,
                    patches=[np.full((5,5),10) for _ in points])
        display=Display();provider=Provider();worker=BEVFusion(provider,self.geometry,display,threading.RLock())
        try:
            worker.start();worker.submit(11,[detection()]);self.assertTrue(entered.wait(1))
            worker.submit(12,[detection()]);worker.submit(13,[detection()]);gate.set()
            deadline=time.monotonic()+2
            while worker.count<2 and time.monotonic()<deadline:time.sleep(.001)
            self.assertEqual(display.frames,[(11,101),(13,102)])
            self.assertEqual(worker.dropped,1);self.assertIsNone(worker.error)
            worker.submit(14,[])
            while worker.count<3 and time.monotonic()<deadline:time.sleep(.001)
            self.assertEqual(display.frames[-1],(14,0))
            self.assertEqual(provider.calls,2)
        finally:gate.set();worker.stop()

    def test_backend_bev2_requires_provider_before_allocating_or_enabling(self):
        fabric=Fabric();fabric.display_registers[0x30]=0x42455632
        backend=LDSNetPerception(fabric.nn,fabric.display,allocator=fabric.allocate,decoder=fabric.decode)
        try:
            with self.assertRaisesRegex(RuntimeError,'snapshot provider'):backend.start()
            self.assertEqual(fabric.buffers,[]);self.assertFalse(fabric.enabled)
        finally:backend.close()

    def test_backend_continues_publishing_nn_results_while_depth_waits(self):
        fabric=Fabric();bev=Display();base=fabric.display
        class CombinedDisplay:
            def read(self,address):
                if address==0x30:return 0x42455632
                return bev.read(address) if address>=0x200 else base.read(address)
            def write(self,address,value):
                if address>=0x200:bev.write(address,value)
                else:base.write(address,value)
        entered=threading.Event();gate=threading.Event()
        class Provider:
            def sample_next(self,points,**kwargs):
                entered.set()
                while not gate.wait(.001):
                    if kwargs['stop'].is_set():raise SnapshotCancelled('test stop')
                return dict(request_id=1,sgm_sequence=7,centers=points,
                    patches=[np.full((5,5),10) for _ in points])
        backend=LDSNetPerception(fabric.nn,CombinedDisplay(),allocator=fabric.allocate,decoder=fabric.decode,timeout=.5)
        backend.configure_bev(Provider(),self.geometry)
        try:
            backend.start();fabric.inject(0,41);backend.perception(timeout=1)
            self.assertTrue(entered.wait(1))
            fabric.inject(1,42)
            deadline=time.monotonic()+1
            while backend._count<2 and time.monotonic()<deadline:time.sleep(.001)
            self.assertEqual(backend._count,2)
            self.assertEqual(fabric.publications,[(0,41),(1,42)])
            self.assertEqual(backend.bev_fusion.count,0)
            self.assertFalse(any(0x200<=a<0x240 for a in fabric.display_registers))
        finally:
            backend.close();gate.set()
        self.assertFalse(any(not buffer.freed for buffer in fabric.buffers))


