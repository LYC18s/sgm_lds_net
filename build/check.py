"""Check the source checkout without installing packages or generating outputs."""
import ast
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def main():
    errors, files, size, python_files = [], 0, 0, 0
    generated = {'.bit', '.hwh', '.dcp', '.xsa', '.so', '.dll', '.exe', '.obj', '.o', '.pt', '.pth', '.onnx', '.zip'}
    for path in ROOT.rglob('*'):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT).as_posix()
        # These paths can legitimately be generated by documented commands.
        if rel.startswith(('build/runtime/', 'build/prediction/', 'src/sgm_yolo/build/', 'src/sgm_yolo/overlay/', 'skill/validation/', 'skill/examples/generated/')) or '__pycache__' in path.parts:
            continue
        files += 1
        size += path.stat().st_size
        if not rel.isascii():
            errors.append('Non-ASCII path: ' + rel)
        if path.is_symlink() or path.is_junction():
            errors.append('Redirected source path: ' + rel)
        if path.suffix.lower() in generated:
            errors.append('Generated artifact in source tree: ' + rel)
        if path.suffix == '.py':
            try:
                ast.parse(path.read_text(encoding='utf-8-sig'), filename=rel)
                python_files += 1
            except SyntaxError as exc:
                errors.append(str(exc))
        if path.suffix == '.md':
            for target in re.findall(r'\]\(([^)]+)\)', path.read_text(encoding='utf-8')):
                if '://' in target or target.startswith('#'):
                    continue
                if not (path.parent / target.split('#')[0]).exists():
                    errors.append('Broken link: ' + rel + ' -> ' + target)
    model = ROOT / 'src/sgm_yolo/models/lds_net'
    hashes = json.loads((model / 'SHA256.json').read_text(encoding='utf-8'))
    for name, expected in hashes.items():
        path = (model / name).resolve()
        if not path.is_relative_to(model.resolve()):
            errors.append('Model path outside bundle: ' + name)
        elif not path.exists() or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            errors.append('Model hash mismatch: ' + name)
    graph = json.loads((model / 'network.json').read_text(encoding='utf-8'))
    if hashlib.sha256((model / 'network.json').read_bytes()).hexdigest() != json.loads((model / 'contract.json').read_text(encoding='utf-8'))['network_sha256']:
        errors.append('Network/driver contract mismatch')
    assert len([n for n in graph['nodes'] if n['op'] == 'conv']) == 37
    project = ROOT / 'src/sgm_yolo'
    ns = {'s': 'http://www.spiritconsortium.org/XMLSchema/SPIRIT/1685-2009'}
    for component in (project / 'hardware/vivado_2017/repo').rglob('component.xml'):
        for node in ET.parse(component).findall('.//s:file/s:name', ns):
            if not (component.parent / node.text).is_file():
                errors.append('Missing IP source: ' + str(component.parent / node.text))
    modules = set()
    for path in (project / 'hardware/rtl').rglob('*.v'):
        modules.update(re.findall(r'\bmodule\s+(\w+)', path.read_text(encoding='utf-8')))
    bd = json.loads((project / 'hardware/vivado_sgm/system/system.bd').read_text(encoding='utf-8'))
    def check_cells(cells):
        for cell in cells.values():
            if ':module_ref:' in cell.get('vlnv', '') and cell['reference_info']['ref_name'] not in modules:
                errors.append('Missing Block Design module: ' + cell['reference_info']['ref_name'])
            check_cells(cell.get('components', {}))
    check_cells(bd['design']['components'])
    if errors:
        raise SystemExit('\n'.join(errors))
    print(f'PASS: {files} source/resource files, {size / 1024**2:.2f} MiB; {python_files} Python files parsed; {len(hashes)} model hashes checked; Markdown links valid.')


if __name__ == '__main__':
    main()
